import type {
  GenerateTriageReportInput,
  GenerateTriageReportReport,
} from "../domain/triage/generateTriageReport.js";
import type { TriageFileReport } from "../domain/triage/triageFile.js";
import { analyzeTriageFile } from "./TriageFile.js";
import type { TriageAnalysisContext } from "./triageSupport.js";

type ReportBody = Omit<GenerateTriageReportReport, "artifact">;
type Triage = Omit<TriageFileReport, "artifact">;

const bullet = (label: string, value: string): string =>
  `- **${label}:** ${value}`;

const formatSection = (triage: Triage): string => {
  if (triage.format === null)
    return "Not an executable image (treated as data).";
  const f = triage.format;
  return [
    bullet(
      "Format",
      `${f.format.toUpperCase()} ${f.bits}-bit ${f.architecture ?? "unknown arch"}`,
    ),
    bullet("Entry point", f.entry_point ?? "n/a"),
    bullet(
      "Imports / Exports / Libraries",
      `${f.imports} / ${f.exports} / ${f.libraries}`,
    ),
    bullet("Overlay", f.has_overlay ? "present" : "none"),
  ].join("\n");
};

const listOrNone = (values: readonly string[]): string =>
  values.length === 0 ? "none observed" : values.join(", ");

const renderMarkdown = (
  path: string,
  sha256: string,
  triage: Triage,
): string => {
  const tags = Object.entries(triage.strings.tag_summary)
    .map(([tag, count]) => `${tag} (${count})`)
    .join(", ");
  return [
    `# Triage report`,
    "",
    bullet("File", `\`${path}\``),
    bullet("Type", triage.file_type),
    bullet("SHA-256", `\`${sha256}\``),
    bullet("MD5", `\`${triage.md5}\``),
    "",
    `## Structure`,
    formatSection(triage),
    "",
    `## Entropy`,
    bullet(
      "File entropy",
      `${triage.entropy.file.toFixed(3)} bits/byte (${triage.entropy.classification})`,
    ),
    bullet(
      "Overlay entropy",
      triage.entropy.overlay === null
        ? "n/a"
        : triage.entropy.overlay.toFixed(3),
    ),
    "",
    `## Toolchain & packing`,
    bullet("Packed indicator", triage.toolchain.packed),
    bullet(
      "Indicators",
      listOrNone(
        triage.toolchain.indicators.map(
          (indicator) =>
            `${indicator.name} (${indicator.category}, ${indicator.confidence})`,
        ),
      ),
    ),
    "",
    `## Capabilities (imports consistent with)`,
    bullet("Capabilities", listOrNone(triage.capabilities.ids)),
    bullet(
      "Runtime symbol resolution",
      triage.capabilities.unresolved_dynamic ? "yes" : "no",
    ),
    "",
    `## Code signature`,
    bullet(
      "Signature",
      triage.code_signature.present
        ? `present (${triage.code_signature.format ?? "unknown"})`
        : "absent",
    ),
    "",
    `## Strings`,
    bullet("Total strings", String(triage.strings.total)),
    bullet("Tagged", tags.length === 0 ? "none" : tags),
    "",
    `## Suggested next steps`,
    ...triage.next_probes.map(
      (probe) => `- \`${probe.operation}\` — ${probe.rationale}`,
    ),
    "",
    `> Static triage inferences, not proof of behavior. Generated by BinSight without executing the target.`,
  ].join("\n");
};

/** Build a shareable Markdown triage report from the one-call triage facets. */
export const analyzeGenerateTriageReport = async (
  bytes: Buffer,
  input: GenerateTriageReportInput,
  context: TriageAnalysisContext,
): Promise<ReportBody> => {
  const triage = await analyzeTriageFile(
    bytes,
    { path: input.path, slice: input.slice },
    context,
  );
  return {
    subject: triage.subject,
    file_type: triage.file_type,
    sha256: context.sha256,
    md5: triage.md5,
    markdown: renderMarkdown(input.path, context.sha256, triage),
    limitations: [
      "The Markdown report restates static triage inferences; it is a shareable summary, not proof of behavior.",
      "The file is read once without executing it, without network access and without writing files.",
    ],
  };
};
